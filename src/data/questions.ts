export function getQuestionsByCategory(category: string): Question[] {
  return allQuestions.filter(q => q.category === category)
}

export function getRandomQuestions(count: number, categories?: string[]): Question[] {
  let pool = categories
    ? allQuestions.filter(q => categories.includes(q.category))
    : allQuestions
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count)
}

/** Shuffles the options of a question so the correct answer appears at a random position.
 *  Returns the shuffled options array and the new correct answer index.
 *  Call this every time a question is about to be displayed to prevent always-B bias.
 */
export function shuffleQuestion(q: Question): { options: string[]; answer: number } {
  const indices = [0, 1, 2, 3]
  // Fisher-Yates shuffle
  for (let i = indices.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[indices[i], indices[j]] = [indices[j], indices[i]]
  }
  const options = indices.map(i => q.options[i])
  const answer = indices.indexOf(q.answer)
  return { options, answer }
}
